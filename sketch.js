    function fadeIn(elements, duration = 400) {
        var els = Array.isArray(elements) ? elements : (elements instanceof NodeList || elements instanceof HTMLCollection ? Array.from(elements) : [elements]);
        var validEls = els.filter(Boolean);
        if (validEls.length === 0) return Promise.resolve();

        return new Promise(function (resolve) {
            var completed = 0;
            validEls.forEach(function (el) {
                el.style.transition = 'opacity ' + duration + 'ms cubic-bezier(0.4, 0, 0.2, 1)';
                el.style.opacity = '0';
                el.style.display = 'block';
                void el.offsetHeight; // Force reflow
                el.style.opacity = '1';

                setTimeout(function () {
                    el.style.transition = '';
                    completed++;
                    if (completed === validEls.length) resolve();
                }, duration);
            });
        });
    }

    // Helper: Fade Out một hoặc nhiều phần tử
    function fadeOut(elements, duration = 300) {
        var els = Array.isArray(elements) ? elements : (elements instanceof NodeList || elements instanceof HTMLCollection ? Array.from(elements) : [elements]);
        var validEls = els.filter(function (el) {
            if (!el) return false;
            var style = window.getComputedStyle(el);
            return style.display !== 'none' && style.visibility !== 'hidden';
        });

        if (validEls.length === 0) {
            els.filter(Boolean).forEach(function (el) { el.style.display = 'none'; });
            return Promise.resolve();
        }

        return new Promise(function (resolve) {
            var completed = 0;
            validEls.forEach(function (el) {
                el.style.transition = 'opacity ' + duration + 'ms cubic-bezier(0.4, 0, 0.2, 1)';
                el.style.opacity = '1';
                void el.offsetHeight; // Force reflow
                el.style.opacity = '0';

                setTimeout(function () {
                    el.style.display = 'none';
                    el.style.transition = '';
                    completed++;
                    if (completed === validEls.length) resolve();
                }, duration);
            });
        });
    }

