    window.playErrorBeep = function () {
        try {
            var audioCtx = new (window.AudioContext || window.webkitAudioContext)();
            var oscillator = audioCtx.createOscillator();
            var gainNode = audioCtx.createGain();
            oscillator.type = 'sawtooth';

            // Short, buzzy error sound
            oscillator.frequency.setValueAtTime(200, audioCtx.currentTime);
            oscillator.frequency.exponentialRampToValueAtTime(100, audioCtx.currentTime + 0.2);

            // Apply volume slider if available
            var volumeSlider = document.querySelector('.settings-option input[type="range"]');
            var vol = volumeSlider ? (volumeSlider.value / 100) : 0.5;

            // Envelope to avoid clicking and fade out quickly
            gainNode.gain.setValueAtTime(vol * 0.3, audioCtx.currentTime); // 0.3 factor so it's not too loud
            gainNode.gain.exponentialRampToValueAtTime(0.001, audioCtx.currentTime + 0.2);

            oscillator.connect(gainNode);
            gainNode.connect(audioCtx.destination);
            oscillator.start();
            oscillator.stop(audioCtx.currentTime + 0.2);
        } catch (e) {
            console.log("Audio API error:", e);
        }
    };

