// Settings Modal Logic
document.addEventListener('DOMContentLoaded', function () {
    var settingsModal = document.getElementById('settings-modal');
    var settingsClose = document.querySelector('.settings-close');

    var languageSelect = document.querySelector('.settings-option select');
    if (languageSelect) {
        languageSelect.addEventListener('change', function (e) {
            var val = e.target.value;
            if (val === 'Tiếng Việt') {
                updateLanguage('vi');
            } else {
                updateLanguage('en');
            }
        });
    }

    if (settingsModal) {
        var allDivs = document.querySelectorAll('div');
        allDivs.forEach(function (div) {
            if (div.textContent.trim().toUpperCase() === 'SETTING' || div.textContent.trim().toUpperCase() === 'STETTING') {
                div.style.cursor = 'pointer';
                div.style.zIndex = '9999';
                div.addEventListener('click', function (e) {
                    e.stopPropagation();
                    settingsModal.classList.add('active');
                });
            }
        });
    }

    if (settingsClose && settingsModal) {
        settingsClose.addEventListener('click', function () {
            settingsModal.classList.remove('active');
        });
    }

    if (settingsModal) {
        window.addEventListener('click', function (event) {
            if (event.target == settingsModal) {
                settingsModal.classList.remove('active');
            }
        });
    }
});
