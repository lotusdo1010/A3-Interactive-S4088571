    window.playToxicEffectSound = function () {
        try {
            var audioCtx = new (window.AudioContext || window.webkitAudioContext)();
            var oscillator = audioCtx.createOscillator();
            var gainNode = audioCtx.createGain();
            oscillator.type = 'triangle';

            // "Drop" or "boom" sound effect
            oscillator.frequency.setValueAtTime(300, audioCtx.currentTime);
            oscillator.frequency.exponentialRampToValueAtTime(50, audioCtx.currentTime + 0.3);

            var volumeSlider = document.querySelector('.settings-option input[type="range"]');
            var vol = volumeSlider ? (volumeSlider.value / 100) : 0.5;

            gainNode.gain.setValueAtTime(vol * 0.5, audioCtx.currentTime);
            gainNode.gain.exponentialRampToValueAtTime(0.001, audioCtx.currentTime + 0.3);

            oscillator.connect(gainNode);
            gainNode.connect(audioCtx.destination);
            oscillator.start();
            oscillator.stop(audioCtx.currentTime + 0.3);
        } catch (e) {
            console.log("Audio API error:", e);
        }
    };

