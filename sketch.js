    function checkOverlap(el1, el2) {
        if (!el1 || !el2) return false;
        if (window.getComputedStyle(el2).display === 'none') return false;
        var r1 = el1.getBoundingClientRect();
        var r2 = el2.getBoundingClientRect();
        return !(r1.right < r2.left ||
            r1.left > r2.right ||
            r1.bottom < r2.top ||
            r1.top > r2.bottom);
    }

